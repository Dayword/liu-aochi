def seed_questions(db: Session) -> None:
    for q in QUESTIONS:
        if len(q) == 8:  # blank/short/code 无选项字段
            qtype, subject, tags, diff, stem, answer, expl, kp = q
            options = []
        else:
            qtype, subject, tags, diff, stem, options, answer, expl, kp = q
        exists = db.query(Question).filter(Question.stem == stem).first()
        if exists:
            continue
        db.add(Question(type=qtype, subject=subject, tags=tags, difficulty=diff,
                        stem=stem, options=options, answer=answer,
                        explanation=expl, knowledge_point=kp))
    db.commit()
